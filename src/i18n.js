export const uiFor = (locale) => copy[locale] ?? copy.zh;

export const getInitialLocale = () => {
  const params = new URLSearchParams(window.location.search);
  const urlLocale = params.get("lang");
  if (urlLocale === "en" || urlLocale === "zh") return urlLocale;
  const savedLocale = window.localStorage.getItem("meteorite-atlas-locale");
  return savedLocale === "en" ? "en" : "zh";
};

export const localizeMeteorite = (meteorite, locale) => {
  const english = englishData.meteorites[meteorite.id];
  const isEnglish = locale === "en" && english;
  return {
    ...meteorite,
    displayName: isEnglish ? meteorite.name.en : meteorite.name.zh,
    secondaryName: isEnglish ? meteorite.name.zh : meteorite.name.en,
    displaySummary: isEnglish ? english.summary : meteorite.summaryZh,
    displayEventLabel: isEnglish ? english.eventLabel : meteorite.event.labelZh,
    displayCountry: isEnglish ? english.country : meteorite.location.countryZh,
    displayRegion: isEnglish ? english.region : meteorite.location.regionZh,
    displayCoordinateRole: isEnglish ? english.coordinateRole : meteorite.location.coordinateRole,
    displayCoverageDescription: isEnglish
      ? english.coverageDescription
      : meteorite.map.coverage.descriptionZh,
  };
};

export const englishTranslationFor = (meteorite) => englishData.meteorites[meteorite.id];
